export const painters: Painter[] = entries
  .map(([id, name, start, end, dates, title, intro, connection, works]) => ({
    id,
    name,
    start,
    end,
    dates,
    title,
    intro,
    connection,
    works,
  }))
  .sort((a, b) => a.start - b.start);
export const overlaps = (
  a: { start: number; end: number },
  b: { start: number; end: number },
) => a.start < b.end && b.start < a.end;
// Pack only the viewed selection, preserving the true lifespan width of every bar.
export function painterRows(selection: Painter[]) {
  const ends: number[] = [];
  return selection.map((painter) => {
    let row = ends.findIndex((end) => end <= painter.start);
    if (row < 0) row = ends.length;
    ends[row] = painter.end;
    return { painter, row };
  });
}
